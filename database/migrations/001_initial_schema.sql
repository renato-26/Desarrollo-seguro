-- Nombres históricos conservados para facilitar el cotejo con MySQL.
CREATE TABLE direcciones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  calle varchar(100) NOT NULL, numero varchar(15) NOT NULL,
  comuna varchar(100) NOT NULL, region varchar(100),
  creado timestamp DEFAULT CURRENT_TIMESTAMP, actualizado timestamp, eliminado timestamp
);
CREATE TABLE restautantes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rut varchar(11) NOT NULL, nombre varchar(200) NOT NULL, fono varchar(45) NOT NULL,
  mapa varchar(200), foto varchar(200), email varchar(100),
  creado timestamp DEFAULT CURRENT_TIMESTAMP, actualizado timestamp, eliminado timestamp,
  direcciones_id integer NOT NULL REFERENCES direcciones(id) ON DELETE RESTRICT
);
CREATE TABLE cartas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(45), orden integer, visible boolean DEFAULT true, foto varchar(200),
  creada timestamp DEFAULT CURRENT_TIMESTAMP, actualizada timestamp, eliminada timestamp,
  restautantes_id integer NOT NULL REFERENCES restautantes(id) ON DELETE RESTRICT
);
CREATE TABLE categorias (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL, visible boolean DEFAULT false, foto varchar(200), orden integer,
  creado timestamp DEFAULT CURRENT_TIMESTAMP, actualizado timestamp, eliminado timestamp,
  cartas_id integer NOT NULL REFERENCES cartas(id) ON DELETE RESTRICT
);
CREATE TABLE items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL, descripcion varchar(300), tiempo varchar(100),
  observaciones varchar(300), precio integer CHECK (precio >= 0),
  visible boolean DEFAULT false, destacado boolean DEFAULT false,
  puntuacion integer DEFAULT 0 CHECK (puntuacion BETWEEN 0 AND 5),
  foto varchar(200), orden integer,
  creado timestamp DEFAULT CURRENT_TIMESTAMP, actualizado timestamp, eliminado timestamp,
  categorias_id integer NOT NULL REFERENCES categorias(id) ON DELETE RESTRICT
);
CREATE TABLE usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(255), email varchar(255),
  password_hash text CHECK (password_hash IS NULL OR password_hash LIKE '$argon2id$%'),
  estado varchar(255), requiere_cambio_password boolean NOT NULL DEFAULT true,
  CHECK (requiere_cambio_password OR password_hash IS NOT NULL)
);
CREATE TABLE comentarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario varchar(255), comentario text,
  id_restaurante integer REFERENCES restautantes(id) ON DELETE RESTRICT
);
CREATE INDEX restautantes_direccion_idx ON restautantes(direcciones_id);
CREATE INDEX cartas_restaurante_idx ON cartas(restautantes_id);
CREATE INDEX categorias_carta_idx ON categorias(cartas_id);
CREATE INDEX items_categoria_idx ON items(categorias_id);
CREATE INDEX comentarios_restaurante_idx ON comentarios(id_restaurante);
